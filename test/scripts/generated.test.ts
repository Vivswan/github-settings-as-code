import { describe, expect, test } from "bun:test";
import { execFileSync } from "node:child_process";
import { cpSync, readFileSync, symlinkSync, writeFileSync } from "node:fs";
import { extname, join } from "node:path";
import {
  GENERATED_OUTPUTS,
  generatedPaths,
  generatorEntryPoint,
  generatorScripts,
} from "../../.github/scripts/generated.js";
import {
  markerSyntaxFor,
  regionNames,
  SYNTAX_BY_EXTENSION,
} from "../../.github/scripts/lib/generated-regions.js";
import { ROOT } from "../root.js";
import { withTempDir } from "../temp-dir.js";

/** Only a file type with a marker syntax carries a region; a marker string anywhere else is test or script text. */
const regionFile = (path: string): boolean => extname(path) in SYNTAX_BY_EXTENSION;

/** The header a wholesale-generated file opens with (gen-gaps-index.ts writes it); read in a file's first lines only, so a generator's own template text does not count as a generated file. */
const WHOLE_FILE_HEADER = /^ \* GENERATED by \S+ - do not edit\./m;

/** Whether a file's first lines carry that header. */
const carriesWholeFileHeader = (text: string): boolean =>
  WHOLE_FILE_HEADER.test(text.split("\n", 4).join("\n"));

/** package.json's scripts, which name every generator. */
const scripts = (
  JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8")) as {
    scripts: Record<string, string>;
  }
).scripts;

/** Every path git tracks, so an untracked file is never read as a generated output. */
const tracked = execFileSync("git", ["ls-files", "-z"], { cwd: ROOT, encoding: "utf8" })
  .split("\0")
  .filter((path) => path !== "");

describe("the generated-output table", () => {
  test("is exactly the tree's generated files: every tracked marker-carrying page plus every header-carrying whole file", () => {
    // A cross-file consistency the table cannot express: a whole file dropped from GENERATED_OUTPUTS would otherwise
    // leave build:check silently blind to it, since nothing but its header says it is generated.
    const texts = new Map(tracked.map((path) => [path, readFileSync(join(ROOT, path), "utf8")]));
    const carrying = tracked.filter(
      (path) =>
        regionFile(path) && regionNames(texts.get(path) ?? "", markerSyntaxFor(path)).length > 0,
    );
    const wholeFiles = tracked.filter((path) => carriesWholeFileHeader(texts.get(path) ?? ""));
    expect(
      GENERATED_OUTPUTS.filter((output) => output.kind === "file")
        .map((output) => output.path)
        .sort(),
    ).toEqual([...wholeFiles].sort());
    expect([...generatedPaths()].sort()).toEqual([...carrying, ...wholeFiles].sort());
  });

  test("every generator is a package.json script over tracked files, and bun run build runs them in table order", () => {
    // build:check runs the generators through their package.json scripts, so a script renamed or dropped there
    // fails every build:check run; build must regenerate the same outputs, in the same order, so a fresh clone
    // builds what CI verifies.
    const generators = generatorScripts();
    for (const generator of generators) {
      const file = generatorEntryPoint(scripts[generator] ?? "");
      expect(
        file,
        `${generator} is a package.json script of the shape bun <file>.ts`,
      ).not.toBeNull();
      expect(tracked, `${generator} runs ${file}`).toContain(file ?? "");
    }
    const built = [...(scripts.build ?? "").matchAll(/bun run (\S+)/g)].map(([, name]) => name);
    expect(built.filter((name) => generators.includes(name ?? ""))).toEqual(generators);
    // The bundle and the library compile src/generated/upstream-gaps.ts, so a gap file added by hand must reach the
    // index before either builds, or one bun run build ships a bundle without it.
    for (const consumer of ["build:bundle", "build:lib"]) {
      expect(built.indexOf("build:gaps-index"), `build:gaps-index before ${consumer}`).toBeLessThan(
        built.indexOf(consumer),
      );
    }
  });

  test("the scan reads the shared marker grammar: an inline HTML marker counts, a marker-shaped scalar does not", () => {
    // A page whose only marker sits mid-line (inputs.md's outputs-list is the tree's inline case) would slip a line-anchored scan.
    expect(
      regionNames("- `result`: <!-- BEGIN GENERATED: a (h) -->x<!-- END GENERATED: a -->", "html"),
    ).toEqual(["a"]);
    expect(regionNames("the words BEGIN GENERATED: a outside a comment\n", "html")).toEqual([]);
    expect(regionNames("inputs:\n  # BEGIN GENERATED: a\n  # END GENERATED: a\n", "yaml")).toEqual([
      "a",
    ]);
    expect(regionNames('d: "one\n  # BEGIN GENERATED: a\n  two"\n', "yaml")).toEqual([]);
  });
});

describe("the build:check runner", () => {
  function git(cwd: string, ...args: string[]): string {
    return execFileSync("git", args, { cwd, encoding: "utf8" });
  }

  /** The runner's exit code and everything it printed on either stream. */
  function runner(cwd: string): { status: number; printed: string } {
    const run = Bun.spawnSync([process.execPath, ".github/scripts/generated.ts"], {
      cwd,
      stdout: "pipe",
      stderr: "pipe",
    });
    return { status: run.exitCode, printed: run.stdout.toString() + run.stderr.toString() };
  }

  /** HEAD's tree in `dir` with its own index, sharing the object store and node_modules; the runner, the generators,
   * and the script table they run through are copied from the working tree, so the code under test is the code
   * being edited. */
  function cloneHead(dir: string): void {
    git(ROOT, "clone", "--quiet", "--shared", ROOT, dir);
    symlinkSync(join(ROOT, "node_modules"), join(dir, "node_modules"));
    cpSync(join(ROOT, "package.json"), join(dir, "package.json"));
    cpSync(join(ROOT, ".github", "scripts"), join(dir, ".github", "scripts"), { recursive: true });
  }

  test(
    "a clean clone passes; a staged stale byte in a page, in action.yml, and in a whole file fails naming each",
    () =>
      withTempDir("build-check-", (dir) => {
        cloneHead(dir);
        const untouched = [
          ".",
          ":(exclude)node_modules",
          ":(exclude).github/scripts",
          ":(exclude)package.json",
        ];

        const clean = runner(dir);
        expect(clean.status).toBe(0);
        expect(clean.printed).not.toContain("drifted");
        expect(git(dir, "status", "--porcelain", "--", ...untouched)).toBe("");

        // A stale byte each region generator repairs (the region shapes hold), and one in a wholesale file.
        const table = join(dir, "docs/reference/sections.md");
        const page = readFileSync(table, "utf8");
        expect(page).toMatch(/^\| `labels` +\|/m);
        writeFileSync(table, page.replace(/^\| `labels`( +)\|/m, "| `labelz`$1|"));
        const inputs = join(dir, "docs/reference/inputs.md");
        const inputsPage = readFileSync(inputs, "utf8");
        expect(inputsPage).toMatch(/^\| `token` +\|/m);
        writeFileSync(inputs, inputsPage.replace(/^\| `token`( +)\|/m, "| `tokem`$1|"));
        const manifest = join(dir, "action.yml");
        const yml = readFileSync(manifest, "utf8");
        expect(yml).toContain('    default: ""\n');
        writeFileSync(manifest, yml.replace('    default: ""\n', '    default: "stale"\n'));
        const index = join(dir, "src/generated/upstream-gaps.ts");
        writeFileSync(index, `${readFileSync(index, "utf8")}\n`);
        git(
          dir,
          "add",
          "docs/reference/sections.md",
          "docs/reference/inputs.md",
          "action.yml",
          "src/generated/upstream-gaps.ts",
        );

        const stale = runner(dir);
        expect(stale.status).toBe(1);
        // git's own --stat lists the four staged stale paths.
        expect(stale.printed).toContain("docs/reference/sections.md");
        expect(stale.printed).toContain("docs/reference/inputs.md");
        expect(stale.printed).toContain("action.yml");
        expect(stale.printed).toContain("src/generated/upstream-gaps.ts");
        // The generators repaired the working tree; only the staged stale copies differ.
        expect(
          git(dir, "diff", "--name-only", "--", ...untouched)
            .trim()
            .split("\n")
            .sort(),
        ).toEqual([
          "action.yml",
          "docs/reference/inputs.md",
          "docs/reference/sections.md",
          "src/generated/upstream-gaps.ts",
        ]);
      }),
    120_000,
  );

  test(
    "a marker no generator registers fails naming its page and region, in either marker syntax, before any generator runs",
    () =>
      withTempDir("build-check-", (dir) => {
        // A generator re-renders only the regions in its own registry, so a region dropped from one keeps its
        // markers and its last body. Staged, the two plants below leave the drift check nothing to diff.
        // inputs.md is the page two generators share: neither one's region may read as unregistered to the other.
        cloneHead(dir);
        const page = join(dir, "docs/reference/inputs.md");
        const retired =
          "<!-- BEGIN GENERATED: retired-grant-table -->\n| grant |\n<!-- END GENERATED: retired-grant-table -->";
        writeFileSync(page, `${readFileSync(page, "utf8")}\n${retired}\n`);
        const manifest = join(dir, "action.yml");
        const retiredKey = "# BEGIN GENERATED: retired-inputs\n# END GENERATED: retired-inputs";
        writeFileSync(manifest, `${readFileSync(manifest, "utf8")}${retiredKey}\n`);
        git(dir, "add", "docs/reference/inputs.md", "action.yml");

        const fix =
          "that no generator registers; register it with a generator, or remove its GENERATED markers";
        expect(runner(dir)).toEqual({
          status: 1,
          printed: [
            `build:check: docs/reference/inputs.md marks a generated region "retired-grant-table" ${fix}`,
            `build:check: action.yml marks a generated region "retired-inputs" ${fix}`,
            "",
          ].join("\n"),
        });
      }),
    120_000,
  );
});
